"""The dbt scoring macros must match public/scoring.js.

Replays shared/scoring_cases.json (generated by scripts/gen_scoring_cases.mjs). The macro SQL is
rendered with plain Jinja and run in local DuckDB; agreement is required to 1e-9.
"""

import json
from pathlib import Path

import duckdb
import pytest
from jinja2 import Template

REPO = Path(__file__).resolve().parent.parent.parent
CASES = json.loads((REPO / "shared" / "scoring_cases.json").read_text())
MACROS = Template((REPO / "pipeline" / "dbt" / "macros" / "scoring.sql").read_text()).module


@pytest.fixture(scope="module")
def con():
    return duckdb.connect()


def test_there_are_enough_cases():
    assert len(CASES["hourBadness"]) >= 40
    assert len(CASES["classify"]) >= 10


def test_hour_badness_macro_matches_js(con):
    cases = CASES["hourBadness"]
    con.execute(
        "create or replace table t (i integer, code integer, pop double, temp double,"
        " wind double, gust double, is_day boolean)"
    )
    con.executemany(
        "insert into t values (?, ?, ?, ?, ?, ?, ?)",
        [
            (i, c["input"]["code"], c["input"]["pop"],
             c["input"]["temp"], c["input"]["wind"], c["input"]["gust"], c["input"]["isDay"])
            for i, c in enumerate(cases)
        ],
    )  # fmt: skip
    sql = MACROS.rainman_badness("code", "pop", "temp", "wind", "gust", "is_day")
    got = dict(con.execute(f"select i, {sql} from t").fetchall())
    for i, case in enumerate(cases):
        assert got[i] == pytest.approx(case["expected"], abs=1e-9), case["input"]


def test_hour_badness_class_matches_js(con):
    for case in CASES["hourBadness"]:
        score = case["expected"]
        sql = MACROS.rainman_class(f"{score!r}::double")
        assert con.execute(f"select {sql}").fetchone()[0] == case["class"], case["input"]


def test_class_macro_matches_js_classify(con):
    for case in CASES["classify"]:
        sql = MACROS.rainman_class(f"{case['score']!r}::double")
        assert con.execute(f"select {sql}").fetchone()[0] == case["expected"], case


def test_class_of_null_is_unknown(con):
    assert con.execute(f"select {MACROS.rainman_class('null::double')}").fetchone()[0] == "unknown"
