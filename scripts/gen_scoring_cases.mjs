// Generates shared/scoring_cases.json from the CURRENT public/scoring.js.
// The accuracy pipeline (pipeline/tests/test_scoring_parity.py) replays these cases against the
// SQL macros rainman_badness / rainman_class, so the dbt scoring stays identical to the app's.
//
// Run: node scripts/gen_scoring_cases.mjs
import { createRequire } from "node:module"
import { writeFileSync, mkdirSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const require = createRequire(import.meta.url)
const here = dirname(fileURLToPath(import.meta.url))
const scoring = require(join(here, "..", "public", "scoring.js"))

const base = { code: 0, pop: 0, temp: 60, wind: 5, gust: 10, isDay: true }
const inputs = []
const add = (over) => inputs.push({ ...base, ...over })

// Every WMO code in the table, in daylight, mild, calm
for (const code of Object.keys(scoring.WMO_BADNESS)) add({ code: Number(code) })
// Codes that are not in the table count as fine (unknown / null codes)
add({ code: 4 })
add({ code: 100 })
add({ code: null })
// Probability floor: pop * 0.5 beats a mild code, and loses to a harsh one
for (const pop of [0, 0.1, 0.3, 0.5, 0.8, 1]) add({ pop })
add({ code: 61, pop: 1 })
add({ code: 65, pop: 0.2 })
add({ pop: null })
// Wind adds, with both boundaries
for (const wind of [20, 20.01, 25, 30, 30.01, 45]) add({ wind })
add({ wind: null })
// Gust add, with the boundary
for (const gust of [45, 45.01, 80]) add({ gust })
add({ gust: null })
add({ wind: 35, gust: 60 })
// Ice: liquid precipitation at or below 34F, but not above, and not for snow or fog
for (const temp of [20, 34, 34.01, 40]) add({ code: 63, temp })
add({ code: 51, temp: 30 })
add({ code: 82, temp: 33 })
add({ code: 73, temp: 25 })
add({ code: 45, temp: 30 })
add({ code: 63, temp: null })
add({ code: 3, temp: 20 })
// Night penalty
add({ isDay: false })
add({ code: 53, isDay: false })
add({ code: 3, pop: 0.4, isDay: false })
add({ isDay: null })
// Clamp at 1
add({ code: 95, wind: 40, gust: 60, isDay: false })
add({ code: 65, wind: 35, isDay: false })
// Combinations
add({ code: 61, pop: 0.9, wind: 22, gust: 50, isDay: false })
add({ code: 2, pop: 0.6, wind: 21, temp: 36 })

// Scores at and around the class boundaries
const scores = [0, 0.05, 0.19999999, 0.2, 0.2000001, 0.35, 0.49999999, 0.5, 0.5000001, 0.8, 1]

const out = {
  _comment: "Generated by scripts/gen_scoring_cases.mjs from public/scoring.js. Do not edit.",
  hourBadness: inputs.map((input) => {
    const expected = scoring.hourBadness(input)
    return { input, expected, class: scoring.classify(expected) }
  }),
  classify: scores.map((score) => ({ score, expected: scoring.classify(score) })),
}

mkdirSync(join(here, "..", "shared"), { recursive: true })
writeFileSync(join(here, "..", "shared", "scoring_cases.json"), JSON.stringify(out, null, 2) + "\n")
console.log(`wrote ${out.hourBadness.length} hourBadness + ${out.classify.length} classify cases`)
